// fulfillPrintOrder(session) -- webhook fulfillment for a paid book order
// (checkout.session.completed with metadata.kind === 'print_order'). Payment
// has cleared, so NOW submit the job to the vendor. Idempotent: a duplicate
// delivery that finds the order already submitted does nothing. Exported and
// called from the Stripe webhook in routes/tokens.js.
// ------------------------------------------------------------
async function fulfillPrintOrder(session, eventId) {
  if (!session || !session.metadata) return;
  const orderId = parseInt(session.metadata.order_id, 10);
  if (!orderId) return;
  const db = await getDb();
  const row = await db.prepare('SELECT * FROM print_orders WHERE id = ?').get(orderId);
  if (!row) return;
  // Idempotency: already submitted to the vendor -> nothing to do.
  if (row.provider_order_id) return;

  // 1) Mark paid + capture the Stripe payment id and (best-effort) card display.
  const paymentIntentId = (session.payment_intent && typeof session.payment_intent === 'object')
    ? session.payment_intent.id : (session.payment_intent || null);
  let cardBrand = null, cardLast4 = null;
  try {
    const card = await stripeProvider.cardForPayment(paymentIntentId);
    if (card) { cardBrand = card.brand || null; cardLast4 = card.last4 || null; }
  } catch (e) {}
  await db.prepare(
    'UPDATE print_orders SET payment_status = ?, status = ?, stripe_payment_intent_id = ?, card_brand = ?, card_last4 = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?'
  ).run('paid', 'paid', paymentIntentId, cardBrand, cardLast4, orderId);
  // Account-lifecycle: a real purchase resets the lone-copper idle clock.
  try { await db.prepare('UPDATE users SET last_purchase_at = ? WHERE id = ?').run(new Date().toISOString(), row.user_id); } catch (e) {}

  // 2) Resolve contact + submit to the vendor now that payment cleared.
  const externalId = row.external_id || ('po-' + orderId);
  let contactEmail = null, contactName = null;
  try {
    const u = await db.prepare('SELECT name, email FROM users WHERE id = ?').get(row.user_id);
    contactEmail = u && u.email ? u.email : null;
    contactName = u && u.name ? u.name : null;
  } catch (e) {}

  try {
    // v3.0.783 -- TD-579. THE PAPER HAS TO SURVIVE THE ROUND TRIP.
    // paper was not passed, and buildSpec ends with `paper: sel.paper === 'cream' ? 'cream' :
    // 'white'` -- so an absent value became WHITE, silently. paper is part of the vendor SKU, so
    // a cream order was quoted as cream, charged as cream and submitted as white, with the row
    // holding the right value and nothing on the submission path reading it. Nothing threw and
    // nothing logged. The column was added in v3.0.667 precisely because paper swaps the SKU and
    // the price; this path never caught up.
    const built = catalog.buildSpec(
      { binding: row.binding, colorTier: row.color_tier, coverFinish: row.cover_finish,
        paper: row.paper || undefined },
      parseInt(row.page_count, 10)
    );
    if (!built.ok) throw new Error('Stored selection invalid: ' + (built.errors || []).join('; '));
    const provider = getPrintProvider();
    const orderReq = buildOrderRequestFromRow(row, built.spec, externalId, contactEmail);
    const placed = await provider.createOrder(orderReq);
    // Tracking is left null until Lulu returns it (picked up by the /order/:id
    // status refresh once the job ships). We deliberately do NOT invent one.
    await db.prepare(
      'UPDATE print_orders SET provider_order_id = ?, status = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?'
    ).run(placed.providerOrderId, placed.status || 'created', orderId);
    if (contactEmail) {
      sendOrderConfirmationEmail({
        to_email: contactEmail, name: contactName,
        order: {
          orderNo: externalId, providerOrderId: placed.providerOrderId,
          bookTitle: row.book_title, orderName: row.order_name, campaignName: row.campaign_name,
          binding: row.binding, colorTier: row.color_tier, coverFinish: row.cover_finish,
          pageCount: row.page_count, quantity: row.quantity,
          total: row.customer_charge, currency: row.currency,
          cardBrand: cardBrand, cardLast4: cardLast4,
          trackingNumber: null, trackingUrl: null,
          shipTo: { name: row.ship_name, street1: row.ship_street1, street2: row.ship_street2, city: row.ship_city, stateCode: row.ship_state, postcode: row.ship_postcode, countryCode: row.ship_country }
        }
      });
    }
  } catch (submitErr) {
    // v3.0.786 -- TD-587. BEFORE CALLING IT A FAILURE, GO AND LOOK.
    // A refusal (4xx) is certain and needs no lookup. Anything else -- a timeout, a 5xx, a dropped
    // socket -- may have created the job anyway, which is exactly what happened to po-7: Cloudflare
    // returned 504, print job 3006840 existed, and we recorded the order as never sent.
    // Three attempts over about half a minute, because Lulu does not necessarily index a new job
    // the instant it is created and asking once would answer "no" too confidently.
    var _refused = !!(submitErr && submitErr.refused);
    if (!_refused) {
      for (var _try = 0; _try < 3; _try++) {
        await new Promise(function (r) { setTimeout(r, 5000 + _try * 5000); });
        var _rec = await recoverPrintJob(db, row);
        if (_rec.found) {
          try {
            console.log('[order-recover] ' + externalId + ' recovered after a failed submit -- the job existed all along');
          } catch (e) {}
          if (contactEmail) {
            sendOrderConfirmationEmail({
              to_email: contactEmail, name: contactName,
              order: {
                orderNo: externalId, providerOrderId: _rec.providerOrderId,
                bookTitle: row.book_title, orderName: row.order_name, campaignName: row.campaign_name,
                binding: row.binding, colorTier: row.color_tier, coverFinish: row.cover_finish,
                pageCount: row.page_count, quantity: row.quantity,
                total: row.customer_charge, currency: row.currency,
                cardBrand: cardBrand, cardLast4: cardLast4,
                trackingNumber: null, trackingUrl: null,
                shipTo: { name: row.ship_name, street1: row.ship_street1, street2: row.ship_street2, city: row.ship_city, stateCode: row.ship_state, postcode: row.ship_postcode, countryCode: row.ship_country }
              }
            });
          }
          return;   // the order succeeded; only the reply was lost
        }
        if (_rec.found === false) break;   // Lulu answered and has nothing: stop asking
      }
    }
    // Paid but the print job did not go -> flag for refund/retry.
    // v3.0.782 -- TD-577. SAY THAT NOTHING REACHED THE PRINTER.
    // order_failed means the SUBMISSION threw: no print job was created, no id was minted,
    // the files were never downloaded, and nothing appears in the vendor dashboard. That is a
    // different event from `rejected`, which means the printer took the job and then refused
    // the files -- and the reader was being told the second story for both. The prefix travels
    // with the row so every surface that shows `error` inherits the distinction instead of
    // each one having to re-derive it.
    // v3.0.786 -- TD-587. THREE OUTCOMES, NOT TWO.
    //   order_failed  -- refused, and the recovery lookup confirmed no job exists. Safe to reorder.
    //   order_unknown -- we could not establish whether a job exists. NOT safe to reorder.
    // v3.0.782 wrote "NOT SENT TO THE PRINTER" on both, which was a promise we could not keep and
    // which sat in front of a Reorder button.
    var _msg = String((submitErr && submitErr.message) || submitErr);
    var _state = _refused ? 'order_failed' : 'order_unknown';
    var _prefix = _refused
      ? 'NOT SENT TO THE PRINTER: '
      : 'MAY OR MAY NOT HAVE REACHED THE PRINTER -- check external id ' + externalId + ': ';
    if (_msg.indexOf('NOT SENT') !== 0 && _msg.indexOf('MAY OR MAY NOT') !== 0) _msg = _prefix + _msg;
    await db.prepare(
      'UPDATE print_orders SET status = ?, error = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?'
    ).run(_state, _msg, orderId);
    if (contactEmail) {
      sendOrderProblemEmail({
        to_email: contactEmail, name: contactName,
        order: {
          orderNo: externalId, bookTitle: row.book_title, orderName: row.order_name,
          campaignName: row.campaign_name, binding: row.binding, colorTier: row.color_tier,
          coverFinish: row.cover_finish, pageCount: row.page_count, quantity: row.quantity
        }
      });
    }
    // v3.0.783 -- TD-582. A SEPARATE REPORT TO SUPPORT, BECAUSE IT IS A SEPARATE AUDIENCE.
    //
    // Ian wants everything needed to research and refund a failed order in one message. The
    // obvious move was to put it in the customer email, which already BCC'd support -- and that
    // is the one thing this file's own rule forbids: TWO AUDIENCES SHARING ONE STRING IS ALWAYS
    // A BUG (TD-513, where 1500 characters of raw model output written for a log reached a
    // reader in a 2.5-second toast). The customer gets a sentence and an action; support gets
    // the Stripe payment id, the amounts and the vendor error. One body cannot serve both.
    //
    // Sent even when contactEmail is missing -- an order whose owner has no email is MORE in
    // need of a report, not less, so this deliberately sits outside the block above.
    //
    // NEVER FATAL, and never silent: the whole point is that a paid order which did not ship
    // must reach a human, so a send failure falls back to the server log carrying the same
    // fields rather than being swallowed.
    try {
      await sendOrderFailureReport({
        orderId: orderId,
        externalId: externalId,
        customerEmail: contactEmail,
        customerName: contactName,
        userId: row.user_id,
        providerOrderId: row.provider_order_id || null,
        amount: row.customer_charge,
        currency: row.currency,
        orderName: row.order_name,
        bookTitle: row.book_title,
        campaignName: row.campaign_name,
        stripePaymentIntentId: paymentIntentId || null,
        stripeSessionId: row.stripe_session_id || null,
        cardBrand: cardBrand, cardLast4: cardLast4,
        binding: row.binding, colorTier: row.color_tier, coverFinish: row.cover_finish,
        paper: row.paper, pageCount: row.page_count, quantity: row.quantity,
        providerCost: row.provider_cost, providerTax: row.provider_tax,
        interiorPdfUrl: row.interior_pdf_url, coverPdfUrl: row.cover_pdf_url,
        error: _msg
      });
    } catch (reportErr) {
      try {
        console.error('[order-failure] the support report could not be sent: ' +
          ((reportErr && reportErr.message) || reportErr) +
          ' -- order ' + externalId + ' user ' + row.user_id + ' <' + (contactEmail || 'no email') + '>' +
          ' charged ' + row.customer_charge + ' ' + row.currency +
          ' stripe_pi ' + (paymentIntentId || 'none') +
          ' lulu ' + (row.provider_order_id || 'none') +
          ' error: ' + _msg);
      } catch (e2) {}
    }
  }
}

