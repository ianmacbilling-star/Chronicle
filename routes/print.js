// Markup is read from app_settings ('print_markup_pct', default 10) and
// applied to the PRINT cost only -- shipping (and tax) pass through at cost.
const DEFAULT_PRINT_MARKUP_PCT = 10;
async function getPrintMarkupPct(db) {
  try {
    const r = await db.prepare("SELECT value FROM app_settings WHERE setting_key = ?").get('print_markup_pct');
    const p = r && r.value != null ? parseFloat(r.value) : NaN;
    return Number.isFinite(p) && p >= 0 ? p : DEFAULT_PRINT_MARKUP_PCT;
  } catch (e) { return DEFAULT_PRINT_MARKUP_PCT; }
}
function applyPrintMarkup(totalCost, printCost, pct) {
  var charge = Number(totalCost || 0) + Number(printCost || 0) * (pct / 100);
  return Math.round(charge * 100) / 100;
}
// Customer-facing charge breakdown.
// v3.0.425 -- MARKUP ON THE PRINT COST BEFORE TAX, AND TAX SHOWN AS ITS OWN LINE.
// The markup used to be applied to Lulu's TAX-INCLUSIVE print cost, so a share of every markup was
// a markup on tax -- small money, wrong on principle, and it made a tax line impossible to reconcile
// with the total. Tax now passes through untouched and is displayed.
// THE TOTAL IS ANCHORED ON WHAT LULU ACTUALLY BILLS US (quote.totalCost) plus the markup, NOT on the
// sum of the parts. If Lulu ever adds a fee that is in its total and in none of the parts we read,
// summing the parts would quietly charge the customer less than the order costs. The residual is
// folded into the print line so the breakdown still adds up exactly, and logged so it cannot hide.
function markedCharge(quote, pct) {
  var r2 = function (n) { return Math.round(Number(n || 0) * 100) / 100; };
  var shipping = r2(quote.shippingCostExclTax != null ? quote.shippingCostExclTax : quote.shippingCost);
  var tax = r2(quote.taxCost);
  var providerTotal = Number(quote.totalCost || 0);
  var totalExcl = Number(quote.totalCostExclTax != null ? quote.totalCostExclTax : (providerTotal - tax)) || 0;
  // v3.0.429 -- THE MARKUP BASE IS EVERYTHING THAT IS NOT SHIPPING AND NOT TAX.
  // A real Lulu quote came back as 8.59 print + 5.69 shipping + 1.20 tax against a total of 16.23:
  // 0.75 unaccounted, which is a provider fee we do not read as its own field. v3.0.425 folded that
  // residual onto the print line at cost. Ian, 2026-08-05: the fee is just part of the price, nobody
  // cares about a separate line, and the markup should apply to it too.
  // Deriving the base from the TOTAL rather than adding up the parts means an unread fee can never
  // again sit outside the markup, whatever Lulu adds next. Shipping still passes at cost, and tax is
  // never marked up -- that was the whole point of v3.0.425.
  var markupBase = r2(totalExcl - shipping);
  if (!(markupBase > 0)) markupBase = r2(quote.printCostExclTax != null ? quote.printCostExclTax : quote.printCost);
  var customerCharge = r2(providerTotal + markupBase * (Number(pct || 0) / 100));
  var printMarked = r2(markupBase * (1 + Number(pct || 0) / 100));
  // Rounding only: the three displayed lines must add up to the charge exactly.
  var residual = r2(customerCharge - (printMarked + shipping + tax));
  if (residual !== 0) printMarked = r2(printMarked + residual);
  return {
    printAtCost: r2(markupBase),
    printMarked: printMarked,
    shipping: shipping,
    tax: tax,
    customerCharge: customerCharge,
  };
}
// v3.0.425 -- ONE LINE PER QUOTE, SO THE TAX QUESTION IS ANSWERABLE FROM A LOG.
// quote.raw was never logged and never stored, so nothing in the system could say whether Lulu was
// reporting tax at all. A tax of 0.00 here means we are NOT collecting it and the margin is paying
// for it; a tax around 8 percent of the order means it was always in the price and merely unshown.
function logQuoteTax(where, quote, m) {
  try {
    console.log('[print-quote] ' + where + ': print ' + Number(quote.printCostExclTax || 0).toFixed(2)
      + ' + shipping ' + Number(quote.shippingCostExclTax || 0).toFixed(2)
      + ' + fees ' + (Number(quote.totalCostExclTax || 0) - Number(quote.printCostExclTax || 0) - Number(quote.shippingCostExclTax || 0)).toFixed(2)
      + ' + tax ' + Number(quote.taxCost || 0).toFixed(2)
      + ' = Lulu total ' + Number(quote.totalCost || 0).toFixed(2)
      + ' ' + (quote.currency || 'USD') + '; customer charged ' + Number(m.customerCharge || 0).toFixed(2)
      + (Number(quote.taxCost || 0) > 0 ? '' : '  [NO TAX REPORTED -- see TD-222]'));
  } catch (e) {}
}

function requireSession(req, res, next) {
  if (!req.session || !req.session.userId) {
    return res.status(401).json({ error: 'Not authenticated' });
  }
  next();
}

// Map the public request body to a neutral OrderRequest the provider takes.
function buildOrderRequest(body, spec, externalId, contactEmail) {
  const s = body.shipTo || {};
  return {
    externalId: externalId,
    title: body.title || 'Campaignia',
    contactEmail: contactEmail || body.contactEmail || '',
    interiorPdfUrl: body.interiorPdfUrl || '',
    coverPdfUrl: body.coverPdfUrl || '',
    spec: spec,
    quantity: Math.max(1, parseInt(body.quantity, 10) || 1),
    shippingLevel: body.shippingLevel || 'cheapest',
    shipTo: {
      name: s.name, street1: s.street1, street2: s.street2,
      city: s.city, postcode: s.postcode, stateCode: s.stateCode,
      countryCode: s.countryCode, phone: s.phone,
    },
  };
}

// Same neutral OrderRequest, but rebuilt from a stored print_orders row (used by
// the webhook fulfillment, where there is no request body).
function buildOrderRequestFromRow(row, spec, externalId, contactEmail) {
  return {
    externalId: externalId,
    title: row.book_title || row.order_name || 'Campaignia',
    contactEmail: contactEmail || '',
    interiorPdfUrl: row.interior_pdf_url || '',
    coverPdfUrl: row.cover_pdf_url || '',
    spec: spec,
    quantity: Math.max(1, parseInt(row.quantity, 10) || 1),
    shippingLevel: row.shipping_level || 'cheapest',
    shipTo: {
      name: row.ship_name, street1: row.ship_street1, street2: row.ship_street2,
      city: row.ship_city, postcode: row.ship_postcode, stateCode: row.ship_state,
      countryCode: row.ship_country, phone: row.ship_phone,
    },
  };
}

