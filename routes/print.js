// Markup is read from app_settings ('print_markup_pct', default 10) and
// applied to the PRINT cost only -- shipping (and tax) pass through at cost.
const DEFAULT_PRINT_MARKUP_PCT = 10;
async function getPrintMarkupPct(db) {
  try {
    const r = await db.prepare("SELECT value FROM app_settings WHERE setting_key = ?").get('print_markup_pct');
    const p = r && r.value != null ? parseFloat(r.value) : NaN;
    return Number.isFinite(p) && p >= 0 ? p : DEFAULT_PRINT_MARKUP_PCT;
  } catch (e) { return DEFAULT_PRINT_MARKUP_PCT; }
}
function applyPrintMarkup(totalCost, printCost, pct) {
  var charge = Number(totalCost || 0) + Number(printCost || 0) * (pct / 100);
  return Math.round(charge * 100) / 100;
}
// Customer-facing charge breakdown.
// v3.0.425 -- MARKUP ON THE PRINT COST BEFORE TAX, AND TAX SHOWN AS ITS OWN LINE.
// The markup used to be applied to Lulu's TAX-INCLUSIVE print cost, so a share of every markup was
// a markup on tax -- small money, wrong on principle, and it made a tax line impossible to reconcile
// with the total. Tax now passes through untouched and is displayed.
// THE TOTAL IS ANCHORED ON WHAT LULU ACTUALLY BILLS US (quote.totalCost) plus the markup, NOT on the
// sum of the parts. If Lulu ever adds a fee that is in its total and in none of the parts we read,
// summing the parts would quietly charge the customer less than the order costs. The residual is
// folded into the print line so the breakdown still adds up exactly, and logged so it cannot hide.
function markedCharge(quote, pct) {
  var r2 = function (n) { return Math.round(Number(n || 0) * 100) / 100; };
  var shipping = r2(quote.shippingCostExclTax != null ? quote.shippingCostExclTax : quote.shippingCost);
  var tax = r2(quote.taxCost);
  var providerTotal = Number(quote.totalCost || 0);
  var totalExcl = Number(quote.totalCostExclTax != null ? quote.totalCostExclTax : (providerTotal - tax)) || 0;
  // v3.0.429 -- THE MARKUP BASE IS EVERYTHING THAT IS NOT SHIPPING AND NOT TAX.
  // A real Lulu quote came back as 8.59 print + 5.69 shipping + 1.20 tax against a total of 16.23:
  // 0.75 unaccounted, which is a provider fee we do not read as its own field. v3.0.425 folded that
  // residual onto the print line at cost. Ian, 2026-08-05: the fee is just part of the price, nobody
  // cares about a separate line, and the markup should apply to it too.
  // Deriving the base from the TOTAL rather than adding up the parts means an unread fee can never
  // again sit outside the markup, whatever Lulu adds next. Shipping still passes at cost, and tax is
  // never marked up -- that was the whole point of v3.0.425.
  var markupBase = r2(totalExcl - shipping);
  if (!(markupBase > 0)) markupBase = r2(quote.printCostExclTax != null ? quote.printCostExclTax : quote.printCost);
  var customerCharge = r2(providerTotal + markupBase * (Number(pct || 0) / 100));
  var printMarked = r2(markupBase * (1 + Number(pct || 0) / 100));
  // Rounding only: the three displayed lines must add up to the charge exactly.
  var residual = r2(customerCharge - (printMarked + shipping + tax));
  if (residual !== 0) printMarked = r2(printMarked + residual);
  return {
    printAtCost: r2(markupBase),
    printMarked: printMarked,
    shipping: shipping,
    tax: tax,
    customerCharge: customerCharge,
  };
}
// v3.0.425 -- ONE LINE PER QUOTE, SO THE TAX QUESTION IS ANSWERABLE FROM A LOG.
// quote.raw was never logged and never stored, so nothing in the system could say whether Lulu was
// reporting tax at all. A tax of 0.00 here means we are NOT collecting it and the margin is paying
// for it; a tax around 8 percent of the order means it was always in the price and merely unshown.
function logQuoteTax(where, quote, m) {
  try {
    console.log('[print-quote] ' + where + ': print ' + Number(quote.printCostExclTax || 0).toFixed(2)
      + ' + shipping ' + Number(quote.shippingCostExclTax || 0).toFixed(2)
      + ' + fees ' + (Number(quote.totalCostExclTax || 0) - Number(quote.printCostExclTax || 0) - Number(quote.shippingCostExclTax || 0)).toFixed(2)
      + ' + tax ' + Number(quote.taxCost || 0).toFixed(2)
      + ' = Lulu total ' + Number(quote.totalCost || 0).toFixed(2)
      + ' ' + (quote.currency || 'USD') + '; customer charged ' + Number(m.customerCharge || 0).toFixed(2)
      + (Number(quote.taxCost || 0) > 0 ? '' : '  [NO TAX REPORTED -- see TD-222]'));
  } catch (e) {}
}

// v3.0.782 -- TD-576. CAN THE PRINTER ACTUALLY GET THESE FILES?
//
// Lulu does not receive our PDFs, it DOWNLOADS them from the urls we hand over, some time
// after the customer has paid. Everything between those two moments is unverified: an object
// that never landed, a signed url whose expiry has passed, a bucket prefix that is not public.
// Every one of those becomes a vendor rejection AFTER the charge, which is the one shape of
// failure this product must not have.
//
// So we do what the vendor will do, from the same side of the network, before charging: ask
// for the file. HEAD first, because it costs nothing; some object stores answer HEAD with 403
// or 405 while serving GET perfectly well, so a refusal falls back to a one-byte ranged GET
// rather than being believed.
//
// THE SNEAKY CASE IS A 200. A missing object behind a proxy answers 200 with an HTML error
// page, which passes every naive "is it reachable" test and then fails at the printer as a
// corrupt PDF. Content-type is therefore checked as well as status -- html is treated as
// absent, because that is what it is.
//
// An INCONCLUSIVE answer is not a refusal. If the check itself times out or throws, the order
// proceeds: refusing to sell someone a book because our own probe was slow would be a worse
// bug than the one this prevents. Only a definite negative stops the sale.
var ORDER_FILE_PROBE_MS = 15000;
async function vendorCanFetch(url) {
  var out = { ok: false, conclusive: false, status: 0, type: '', detail: '' };
  if (!(typeof url === 'string' && /^https?:\/\//i.test(url))) {
    out.conclusive = true; out.detail = 'not a fetchable url';
    return out;
  }
  var ctl = null, timer = null;
  try {
    ctl = new AbortController();
    timer = setTimeout(function () { try { ctl.abort(); } catch (e) {} }, ORDER_FILE_PROBE_MS);
    var res = await fetch(url, { method: 'HEAD', signal: ctl.signal, redirect: 'follow' });
    if (res.status === 403 || res.status === 405 || res.status === 501) {
      res = await fetch(url, { method: 'GET', headers: { Range: 'bytes=0-0' }, signal: ctl.signal, redirect: 'follow' });
    }
    out.status = res.status;
    out.type = String(res.headers.get('content-type') || '').toLowerCase();
    if (res.status >= 200 && res.status < 300) {
      if (out.type.indexOf('html') !== -1) {
        out.conclusive = true; out.detail = 'the url answers with a web page, not a file';
      } else {
        out.ok = true; out.conclusive = true;
      }
    } else if (res.status >= 400 && res.status < 500) {
      out.conclusive = true; out.detail = 'the printer would get HTTP ' + res.status;
    } else {
      out.detail = 'HTTP ' + res.status;   // 5xx: the host is unwell, not the file. Inconclusive.
    }
  } catch (e) {
    out.detail = (e && e.name === 'AbortError') ? 'the check timed out' : ((e && e.message) || 'unreachable');
  } finally {
    if (timer) clearTimeout(timer);
  }
  return out;
}
// v3.0.786 -- TD-587. GO AND SEE WHETHER THE JOB WE MAY HAVE CREATED EXISTS.
//
// The one thing that turns a lost reply into a non-event. Asks Lulu for the job stamped with this
// order's external_id and, if it is there, records it exactly as the successful path would have.
//
// RETURNS one of three answers, and the third is the point:
//   { found: true,  ... }  the job exists and the row now holds its id
//   { found: false }       Lulu answered and has nothing -- the order really was not created
//   { unknown: true }      Lulu could not be asked, so nothing has been learned
// Collapsing the last two is the bug this exists to fix, one level down in _fetch. A recovery that
// reports "no job" because the network was unwell would send a reader to press Reorder on a book
// already in production.
//
// IDEMPOTENT AND SAFE TO CALL OFTEN. It only ever WRITES a provider_order_id where there is none,
// and the UPDATE says so in its WHERE clause, so two callers racing cannot produce two answers.
async function recoverPrintJob(db, row) {
  if (!row) return { unknown: true };
  if (row.provider_order_id) return { found: true, providerOrderId: row.provider_order_id, already: true };
  var externalId = row.external_id || ('po-' + row.id);
  try {
    var provider = getPrintProvider();
    if (typeof provider.findOrderByExternalId !== 'function') return { unknown: true };
    var live = await provider.findOrderByExternalId(externalId);
    if (!live || !live.providerOrderId) return { found: false };
    await db.prepare(
      'UPDATE print_orders SET provider_order_id = ?, status = ?, tracking_url = ?, carrier = ?, ' +
      'error = NULL, updated_at = CURRENT_TIMESTAMP WHERE id = ? AND provider_order_id IS NULL'
    ).run(live.providerOrderId, live.status || 'created', live.trackingUrl || null, live.carrier || null, row.id);
    row.provider_order_id = live.providerOrderId;
    row.status = live.status || 'created';
    row.error = null;
    try {
      console.log('[order-recover] ' + externalId + ' was already at the printer as job ' +
        live.providerOrderId + ' -- adopted' +
        ((live.duplicateCount > 1) ? (' (WARNING: ' + live.duplicateCount + ' jobs carry this external id)') : ''));
    } catch (e) {}
    return { found: true, providerOrderId: live.providerOrderId, status: row.status,
             duplicateCount: live.duplicateCount || 1 };
  } catch (e) {
    try { console.warn('[order-recover] could not ask the printer about ' + externalId + ': ' + ((e && e.message) || e)); } catch (e2) {}
    return { unknown: true, detail: (e && e.message) || String(e) };
  }
}
// v3.0.787 -- TD-587b. NARROWED TO THE STATES THAT ACTUALLY NEED IT.
// v3.0.786 asked about any paid order with no job id -- which includes an order still being
// submitted, because fulfillPrintOrder marks the row paid and THEN submits. On a slow vendor that
// window is a minute and a half, and the sweep would race a request that is still in flight.
// Harmless (the write is guarded on provider_order_id IS NULL) but pointless, and it muddies the
// log with lookups for orders that are simply not finished yet.
// The AUTOMATIC triggers use this. The BUTTON uses orderCanBeChecked below, which is wider.
function orderNeedsRecovery(row) {
  return !!(row && !row.provider_order_id &&
    (row.payment_status === 'paid' || row.payment_status === 'refunded') &&
    (row.status === 'order_failed' || row.status === 'order_unknown'));
}
// The button may ask about ANY paid order with no job, including one stranded at 'paid' because
// the process died between the payment write and the submit. Nothing automatic will ever look at
// that row -- it never reaches a failure state -- so a deliberate human check is its only way
// back, and a human pressing a button cannot race an in-flight submit the way a sweep can.
function orderCanBeChecked(row) {
  return !!(row && !row.provider_order_id &&
    (row.payment_status === 'paid' || row.payment_status === 'refunded'));
}
// v3.0.787 -- TD-588. KEEP A LIVE ORDER CURRENT, which is how tracking ever appears.
//
// getOrderStatus has always known how to read tracking and GET /order/:id has always known how to
// store it -- and NOTHING IN THE CLIENT CALLS THAT ROUTE. The orders screen reads the list, which
// reads the database and asks the vendor nothing. So `tracking_url` stayed null forever, the card
// said "Awaiting Tracking" indefinitely, and the Track Shipment link could not appear on any
// order however far it got. A correct function with no caller, the same shape as TD-585's
// _skuError and the v3.0.726 tour.
//
// Only for orders that are LIVE AND UNFINISHED: shipped and delivered are terminal, and a
// rejected or cancelled job will not change on its own either. Best-effort throughout -- a vendor
// that is slow or down must never stop an order rendering.
var ORDER_LIVE_STATES = ['created', 'accepted', 'in_production', 'paid'];
function orderIsLive(row) {
  return !!(row && row.provider_order_id && ORDER_LIVE_STATES.indexOf(String(row.status)) !== -1);
}
async function refreshLiveOrder(db, row) {
  if (!orderIsLive(row)) return false;
  try {
    var provider = getPrintProvider();
    var live = await provider.getOrderStatus(row.provider_order_id);
    if (!live) return false;
    var _st = live.status || row.status;
    var _url = live.trackingUrl || row.tracking_url || null;
    var _num = live.trackingNumber || row.tracking_number || null;
    var _car = live.carrier || row.carrier || null;
    // Write only when something actually moved: an UPDATE per render would churn updated_at and
    // make "when did this last change" meaningless.
    if (_st === row.status && _url === (row.tracking_url || null) &&
        _num === (row.tracking_number || null) && _car === (row.carrier || null)) return false;
    await db.prepare(
      'UPDATE print_orders SET status = ?, tracking_url = ?, tracking_number = ?, carrier = ?, ' +
      'updated_at = CURRENT_TIMESTAMP WHERE id = ?'
    ).run(_st, _url, _num, _car, row.id);
    row.status = _st; row.tracking_url = _url; row.tracking_number = _num; row.carrier = _car;
    return true;
  } catch (e) {
    try { console.warn('[order-refresh] ' + (row.external_id || row.id) + ': ' + ((e && e.message) || e)); } catch (e2) {}
    return false;
  }
}
function requireSession(req, res, next) {
  if (!req.session || !req.session.userId) {
    return res.status(401).json({ error: 'Not authenticated' });
  }
  next();
}

// Map the public request body to a neutral OrderRequest the provider takes.
function buildOrderRequest(body, spec, externalId, contactEmail) {
  const s = body.shipTo || {};
  return {
    externalId: externalId,
    title: body.title || 'Campaignia',
    contactEmail: contactEmail || body.contactEmail || '',
    interiorPdfUrl: body.interiorPdfUrl || '',
    coverPdfUrl: body.coverPdfUrl || '',
    spec: spec,
    quantity: Math.max(1, parseInt(body.quantity, 10) || 1),
    shippingLevel: body.shippingLevel || 'cheapest',
    shipTo: {
      name: s.name, street1: s.street1, street2: s.street2,
      city: s.city, postcode: s.postcode, stateCode: s.stateCode,
      countryCode: s.countryCode, phone: s.phone,
    },
  };
}

// Same neutral OrderRequest, but rebuilt from a stored print_orders row (used by
// the webhook fulfillment, where there is no request body).
function buildOrderRequestFromRow(row, spec, externalId, contactEmail) {
  return {
    externalId: externalId,
    title: row.book_title || row.order_name || 'Campaignia',
    contactEmail: contactEmail || '',
    interiorPdfUrl: row.interior_pdf_url || '',
    coverPdfUrl: row.cover_pdf_url || '',
    spec: spec,
    quantity: Math.max(1, parseInt(row.quantity, 10) || 1),
    shippingLevel: row.shipping_level || 'cheapest',
    shipTo: {
      name: row.ship_name, street1: row.ship_street1, street2: row.ship_street2,
      city: row.ship_city, postcode: row.ship_postcode, stateCode: row.ship_state,
      countryCode: row.ship_country, phone: row.ship_phone,
    },
  };
}

